/**
 * Inline SVG icons for the invite / referral-share page.
 *
 * These used to be Bootstrap Icons glyphs (`<i className="bi bi-share">`),
 * which render through the `bootstrap-icons` WEB FONT loaded by index.html.
 * A tester on an iPhone saw the share, SMS, email and WhatsApp icons never
 * appear while the button text rendered normally — the signature of a web
 * font that never applied. On iOS every browser (Chrome included) is WebKit,
 * and web fonts are exactly the resource class that Lockdown Mode and the
 * "block web fonts" rule sets in iOS content blockers switch off. When that
 * happens the `content: "\f52e"` on `.bi-share::before` falls back to a
 * system font, where U+F52E is an empty Private Use Area codepoint, so the
 * icon silently becomes nothing. The families this app serves are also on
 * school and public networks where DNS/proxy filtering is common.
 *
 * Inline SVG has no network dependency at all: the markup ships inside the JS
 * bundle, so there is nothing left to block, 404, or fail to decode. Keep it
 * that way — do not reintroduce `<i className="bi …">`, an `<img src>`, or a
 * `<use href="…#sprite">` here, all of which are separately fetchable.
 *
 * Every icon is decorative: each control it sits in carries its own visible
 * text label, so the icons are `aria-hidden` and the accessible name comes
 * from that text. A blocked icon therefore never leaves an unlabelled button.
 *
 * Path data is Bootstrap Icons v1.13.1 (MIT, https://icons.getbootstrap.com/).
 */
